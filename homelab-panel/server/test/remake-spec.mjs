// ---------------------------------------------------------------------------
//  ══ سندِ ریمیک زنده است، نه یک کاغذِ تزئینی ══════════════════════════════
//
//  خواستهٔ صاحب سامانه (۱۴۰۵/۰۷/۰۹): «تمامِ آن پرامپت باید با دقت درست
//  بشود، نه حدس… اگر می‌گویی نمی‌شود، یک راهِ حلِ درست بساز.»
//
//  راهِ حل `docs/REMAKE-fa.md` شد. ولی سندی که کسی نسنجد، فردا با کد جور
//  نیست و از نبودنش بدتر است — آدم را دنبالِ چیزی می‌فرستد که عوض شده.
//
//  پس این پرونده خودِ سند را می‌سنجد:
//    ۱) شش گام سرِ جایشان‌اند
//    ۲) هر بند حال دارد، و «شد» بی نامِ آزمون نوشته نشده
//    ۳) آزمونی که ادعا شده واقعاً وجود دارد
//    ۴) ده قاعدهٔ ربات‌ها دست‌نخورده‌اند
// ---------------------------------------------------------------------------
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.join(here, '..', '..', '..');
const doc = fs.readFileSync(path.join(repo, 'docs', 'REMAKE-fa.md'), 'utf8');

let pass = 0, fail = 0;
const check = (name, ok, detail = '') => {
  if (ok) { pass++; console.log(`  ✅ ${name}`); }
  else { fail++; console.log(`  ❌ ${name}${detail ? ` — ${detail}` : ''}`); }
};

console.log('\n══ سندِ ریمیک ══\n');

//  ── ۱) شش گام ──────────────────────────────────────────────────────────
const steps = [...doc.matchAll(/^## گامِ ([۰-۹]+)/gm)].map((m) => m[1]);
check('هر شش گام سرِ جایشان‌اند', steps.length === 6, `${steps.length} گام: ${steps.join(' ')}`);

//  ── ۲) هر بندِ جدول حال دارد ────────────────────────────────────────────
/*
 *  ⚠️ فقط سطرهایی که شمارهٔ بند دارند (`| ۱.۲ |`)، نه سربرگ و نه جدولِ
 *  توضیحی. وگرنه هر جدولِ تازه‌ای در این سند آزمون را الکی سرخ می‌کرد.
 */
const rows = [...doc.matchAll(/^\| ([۰-۹]+\.[۰-۹]+(?:-[^\s|]+)?) \| ([^|]+)\| ([^|]+)\| ([^|]+)\|/gm)];
check('بندهای شماره‌دار پیدا شدند', rows.length >= 25, `${rows.length} بند`);

const ALLOWED = ['نشده', 'در دست', 'شد', 'نشد', 'نیمه', 'هست'];
for (const [, id, , , stateRaw] of rows) {
  const state = stateRaw.replace(/\*/g, '').trim();
  const known = ALLOWED.some((a) => state.startsWith(a));
  if (!known) check(`بندِ ${id} حالِ شناخته‌شده دارد`, false, `«${state}»`);
}
check('همهٔ بندها حالِ شناخته‌شده دارند',
  rows.every(([, , , , st]) => ALLOWED.some((a) => st.replace(/\*/g, '').trim().startsWith(a))));

/*
 *  ⛔ **بندِ اصلیِ این پرونده.**
 *
 *  «شد» بی نامِ آزمون یعنی ادعا. همان «کلکِ دروغ»ی که در این مخزن قدغن
 *  است — و یک بار همین‌جا هم نزدیک بود: میزِ کدها را ساختیم و «شد»
 *  نوشتیم، در حالی که نبض نداشت.
 */
const done = rows.filter(([, , , , st]) => st.replace(/\*/g, '').trim().startsWith('شد'));
check('بندهای «شد» پیدا شدند', done.length >= 5, `${done.length} بند`);
for (const [, id, , , stateRaw] of done) {
  const st = stateRaw.trim();
  check(`بندِ ${id} نامِ آزمونش را آورده`, /—\s*\S/.test(st) || /`[^`]+`/.test(st), st);
}

//  ── ۳) آزمونی که ادعا شده، وجود دارد ────────────────────────────────────
const claimed = new Set([...doc.matchAll(/`([a-z0-9-]+\.(?:mjs|test\.js))`/g)].map((m) => m[1]));
check('سند نامِ آزمون برده', claimed.size >= 2, [...claimed].join(' · '));
for (const name of claimed) {
  const inPanel = fs.existsSync(path.join(here, name));
  const inShop = fs.existsSync(path.join(repo, '..', 'shop', 'server', 'test', name));
  /*
   *  ⚠️ آزمونِ ریپوی خواهر ممکن است کنارِ این مخزن نباشد (سیزنی که فقط
   *  همین را کلون کرده). نبودنِ **پوشه** ایراد نیست؛ نبودنِ فایل وقتی
   *  پوشه هست، ایراد است.
   */
  const shopHere = fs.existsSync(path.join(repo, '..', 'shop', 'server', 'test'));
  check(`آزمونِ «${name}» واقعاً هست`, inPanel || inShop || !shopHere,
    'نامِ آزمونی در سند که فایلش نیست');
}

//  ── ۴) ده قاعدهٔ ربات‌ها ────────────────────────────────────────────────
console.log('\n── طرحِ ربات‌ها ──\n');
const bots = doc.slice(doc.indexOf('## گامِ ۵'), doc.indexOf('## گامِ ۶'));
const RULES = [
  ['هیچ رباتی زمان‌بندِ خودش را نمی‌سازد', /setInterval` تازه ندارد/],
  ['هیچ اجرایی بی ثبت نمی‌ماند', /automation_runs/],
  ['دفترِ دوم ساخته نمی‌شود', /دفترِ دوم نمی‌سازد/],
  ['رمز خوانده نمی‌شود', /هیچ‌وقت رمز نمی‌خواند/],
  ['یک خبر برای یک حال', /یک خبر برای یک حال/],
  ['سرورِ خواب ⇒ هشدار نه سکوت', /هشدار، نه سکوت/],
  ['سقفِ نرخ پر نمی‌شود', /۴۲۹/],
  ['هر یافته یک رویداد است', /ctx\.emit/],
  ['تنها کارِ درست‌کننده، فرستادنِ دوبارهٔ کد', /فرستادنِ دوبارهٔ کد/],
  ['بی مدل هم کار می‌کند', /بی مدلِ هوش مصنوعی هم کار می‌کند/],
];
for (const [name, re] of RULES) check(`قاعده: ${name}`, re.test(bots));

//  ⛔ و سه ربات با نامِ دقیقشان، تا سیزنِ بعدی نامِ دیگری نسازد
for (const bot of ['pump-watch', 'shop-watch', 'login-watch', 'code-rescue']) {
  check(`رباتِ «${bot}» نام‌گذاری شده`, bots.includes(bot));
}

/*
 *  ⛔ و عددها در سند باشند، نه در سرِ کسی: پانزده دقیقه، پنج دقیقه،
 *  بیست‌وشش ساعت. عددِ بی‌سند همان حدسی است که قدغن شد.
 */
check('عددهای زمان‌بندی در سند نوشته شده‌اند',
  /هر ۱۵ دقیقه/.test(bots) && /هر ۵ دقیقه/.test(bots) && /۲۶ ساعت/.test(bots));

console.log('\n════════════════════════════════════');
console.log(`  ✅ ${pass} سبز، ${fail} قرمز`);
console.log('════════════════════════════════════\n');
process.exit(fail === 0 ? 0 : 1);
