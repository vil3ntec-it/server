// ---------------------------------------------------------------------------
//  ثبتِ خودکارِ برنامه — باز، ولی نه بی‌انتها
//
//  ⚠️ این فایل از یک آزمونِ واقعی درآمد. مسیرهای کد، برنامهٔ ناشناخته را
//  *پیش از* هر بررسیِ کلید در دفتر ثبت می‌کردند:
//
//      ۲۰ درخواستِ بی‌کلید با نامِ ساختگی → ۲۰ ردیفِ تازه در دفتر
//
//  یعنی هر کسی از اینترنت می‌توانست جدولِ برنامه‌ها را پر کند و فهرستِ پنل
//  را غیرِقابلِ استفاده.
//
//  ولی بستنِ کاملش هم غلط بود و آزمون‌ها همان لحظه گفتند: برنامه‌ای که
//  نامِ برنامه نمی‌فرستد روی «main» می‌افتد و باید کار کند. یعنی «هیچ
//  برنامه‌ای پشتِ در نماند» یک خواستهٔ واقعی است، نه سهل‌انگاری.
//
//  پس نه باز و نه بسته: محدود.
//
//    • نام‌های همیشه‌باز (main) بی‌قید‌وشرط
//    • بقیه: چند تا در ساعت، و نه بیشتر
//
//  مهاجم به‌جای هزاران ردیف، چند تا در ساعت می‌گیرد؛ برنامهٔ واقعیِ تازه
//  همان بارِ اول ثبت می‌شود و کسی پشتِ در نمی‌ماند.
// ---------------------------------------------------------------------------

/** نام‌هایی که همیشه ساخته می‌شوند — پیش‌فرضِ کلاینت‌هایی که چیزی نمی‌فرستند */
const ALWAYS = new Set(['main']);

const HOUR = 3600_000;

/**
 * چند برنامهٔ ناشناخته در یک ساعت خودکار ثبت شود.
 *
 * ⚠️ عدد سخاوتمندانه است و عمدی: صاحبِ سرور ممکن است چند برنامه و سایت
 * را در یک نشست اولین بار وصل کند، و اگر آن‌جا «ثبت نشده» بگیرد، دنبالِ
 * باگی می‌گردد که وجود ندارد. ده تا در ساعت هم آن حالت را پوشش می‌دهد و
 * هم جلوی پر شدنِ جدول را می‌گیرد (مهاجم به‌جای هزاران ردیف، ده تا).
 */
const MAX_PER_HOUR = Number(process.env.HLP_AUTO_REGISTER_PER_HOUR ?? 10);

/** زمانِ ثبت‌های اخیر */
let recent = [];

/**
 * آیا اجازه هست این نام خودکار ثبت شود؟
 *
 * ⚠️ فقط وقتی صدا زده شود که برنامه واقعاً نیست — هر صدا زدن یک جا از
 * سهمیه برمی‌دارد.
 */
export function allowAutoRegister(slug) {
  if (ALWAYS.has(String(slug || '').trim().toLowerCase())) return true;
  if (MAX_PER_HOUR <= 0) return false;

  const now = Date.now();
  recent = recent.filter((t) => t > now - HOUR);
  if (recent.length >= MAX_PER_HOUR) return false;

  recent.push(now);
  return true;
}

/** فقط برای آزمون‌ها */
export function resetAutoRegister() {
  recent = [];
}

export function autoRegisterStatus() {
  const now = Date.now();
  recent = recent.filter((t) => t > now - HOUR);
  return { usedThisHour: recent.length, maxPerHour: MAX_PER_HOUR };
}
