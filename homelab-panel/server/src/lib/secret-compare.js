// ---------------------------------------------------------------------------
//  مقایسهٔ رازها — همیشه با زمانِ ثابت
//
//  ⚠️ چرا `a === b` کافی نیست: مقایسهٔ رشته در جاوااسکریپت سرِ اولین بایتِ
//  متفاوت برمی‌گردد. یعنی مدتِ پاسخ می‌گوید چند بایتِ اول درست بوده‌اند، و
//  با تکرارِ کافی می‌شود کلید را بایت‌به‌بایت ساخت.
//
//  روی اینترنتِ پرنویز این حمله سخت است — ولی سرور روی شبکهٔ خانگی هم باز
//  است و آن‌جا نویز تقریباً صفر. و هزینهٔ درست انجام دادنش همین چند خط است.
//
//  ⚠️ و طولِ رشته خودش نشت می‌کند: timingSafeEqual روی دو بافرِ نابرابر
//  استثنا می‌دهد. پس اول هر دو را هش می‌کنیم تا همیشه ۳۲ بایت باشند.
// ---------------------------------------------------------------------------
import crypto from 'node:crypto';

/**
 * آیا این دو راز یکی‌اند؟ — بدونِ نشتِ زمانی
 *
 * @param {string|null|undefined} given   آنچه کاربر فرستاده
 * @param {string|null|undefined} expected آنچه باید باشد
 */
export function sameSecret(given, expected) {
  const a = String(given ?? '');
  const b = String(expected ?? '');
  // رازِ خالی هیچ‌وقت درست نیست — وگرنه برنامهٔ بی‌کلید همه‌چیز را باز می‌کرد
  if (!a || !b) return false;
  const ha = crypto.createHash('sha256').update(a).digest();
  const hb = crypto.createHash('sha256').update(b).digest();
  return crypto.timingSafeEqual(ha, hb);
}
