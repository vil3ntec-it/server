//
//  ⚠️ فرستادنِ کد از این‌جا رفت. حالا یک موتور این کار را می‌کند —
//  server/src/codes/ — با صف، تلاشِ دوباره، و فهرستی که در پنل دیده می‌شود.
//
//  سرویس‌های پیامک (کاوه‌نگار، sms.ir، ملی‌پیامک، قاصدک و webhook) هم با آن
//  برداشته شدند: خواستهٔ صاحبِ سرور این بود که کدها فقط ایمیلی باشند.
//
//  فقط `mask` مانده، چون چند جای دیگر برای لاگ از آن استفاده می‌کنند و
//  کپی‌کردنش در سه فایل بدتر از ماندنش این‌جاست.
// ---------------------------------------------------------------------------

/** برای لاگ: al***@example.com — نشانیِ کامل در لاگ نمی‌ماند */
export function mask(value) {
  const s = String(value || '');
  if (s.includes('@')) {
    const [name, domain] = s.split('@');
    return `${name.slice(0, 2)}***@${domain}`;
  }
  return s.length > 7 ? `${s.slice(0, 5)}***${s.slice(-3)}` : s;
}
