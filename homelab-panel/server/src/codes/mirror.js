// ---------------------------------------------------------------------------
//  آینهٔ کدهای سرورِ حساب — «کد همان‌جا که ساخته می‌شود دیده شود»
//
//  خواستهٔ صریحِ صاحب سامانه (۱۴۰۵/۰۷/۱۰): «نگفتم یک صفحه باشه که کدهایی
//  که ساخته می‌شه اول اون‌جا بیان و بعد بره به ایمیل؟ چرا کد اون‌جا نمیاد…
//  در جا کد نشون بده.»
//
//  ── چه چیزی عوض شد و چه چیزی نشد ────────────────────────────────────
//  کدهای خودِ پنل از روزِ اول در فهرست دیده می‌شدند (`revealCode(row)` در
//  `routes/codes.js`). آن‌چه دیده نمی‌شد کدهای **سرورِ حساب** بود — یعنی
//  کدِ هر سه برنامه، یعنی عملاً همهٔ کدهایی که صاحبِ سامانه می‌بیند. پس
//  صفحه از دیدِ او همیشه بی‌کد بود.
//
//  ⛔ **و قاعدهٔ ۱۴۰۵/۰۷/۰۴ («در فهرست هیچ کدی نمی‌آید») دلیلش این نبود که
//  کد راز است** — دلیلش دفترِ ممیزی بود: «هر تازه‌شدنِ دو‌ونیم‌ثانیه‌ای یک
//  ردیفِ ‹کد دیده شد› برای هر مشتری می‌ساخت و آن دفتر بی‌معنا می‌شد».
//  یعنی مسئله **تکرار** بود، نه خودِ دیدن. پس این‌جا همان تکرار بسته شد و
//  خواستهٔ صاحبِ سامانه برآورده:
//
//      هر کد **یک بار** از سرورِ حساب پرسیده می‌شود و در حافظه می‌ماند.
//
//  ⇒ دفترِ ممیزی برای هر کد **یک** ردیف دارد، مو‌به‌مو مثلِ یک کلیکِ دستی.
//  صد بار تازه شدنِ صفحه هیچ ردیفِ تازه‌ای نمی‌سازد.
//
//  ── قاعده‌هایی که نباید پس بروند ─────────────────────────────────────
//  ⛔ **هیچ دفترِ دومی ساخته نشد**: این فقط یک `Map` در حافظهٔ همین پروسه
//     است. روی دیسک نمی‌نشیند، در پشتیبان نمی‌آید، و با هر بار بالا آمدنِ
//     پنل خالی است — همان قاعدهٔ «راز روی دیسک ننشیند».
//  ⛔ **فقط کدِ زنده.** کدِ مصرف‌شده یا منقضی هیچ‌وقت پرسیده نمی‌شود و
//     ردیفِ کَش‌شده‌اش با گذشتنِ وقت خودش پاک می‌شود.
//  ⛔ **سقف دارد** (`MAX_PER_PASS`): بارِ اولِ یک فهرستِ شصت‌تایی نباید
//     شصت درخواست به سرورِ حساب بزند — همان «ازدحامِ سرد»ی که ۱.۵۰.۲ بست.
//     تازه‌ترین‌ها اول، و بقیه در دورِ بعد.
//  ⛔ **هیچ‌وقت استثنا بیرون نمی‌دهد**: کد رفاه است، خودِ فهرست اصل. سرورِ
//     حسابِ کهنه‌ای که مسیرِ نمایش ندارد فقط یعنی همان دکمهٔ دستیِ قبلی.
// ---------------------------------------------------------------------------

/** بیشترین کدی که در یک بار تازه شدنِ فهرست از سرورِ حساب پرسیده می‌شود */
export const MAX_PER_PASS = 12;

/** کلیدِ هر کد — دفترش هم در کلید است، چون شناسه‌ها بینِ دو دفتر تکراری‌اند */
export const keyOf = (source, id) => `${source}:${id}`;

/** `Map<key, { code, expiresAt }>` — فقط در حافظه، هیچ‌وقت روی دیسک */
const seen = new Map();

/** کدی که پیش از این یک بار پرسیده شده و هنوز زنده است */
export function cachedCode(source, id, now = Date.now()) {
  const hit = seen.get(keyOf(source, id));
  if (!hit) return null;
  if (hit.expiresAt && hit.expiresAt <= now) {
    seen.delete(keyOf(source, id));
    return null;
  }
  return hit.code;
}

/** نگه داشتنِ کدی که همین الان یک بار پرسیده شد */
export function rememberCode(source, id, code, expiresAt) {
  if (!code) return;
  seen.set(keyOf(source, id), { code: String(code), expiresAt: Number(expiresAt) || 0 });
}

/**
 *  پاک کردنِ کدهای مرده.
 *
 *  ⚠️ بی این، پنلی که ماه‌ها بالا می‌ماند هر کدی را که تا حالا دیده در
 *  حافظه نگه می‌داشت. کدِ منقضی هیچ ارزشی ندارد و ماندنش فقط خرج است.
 */
export function pruneCodes(now = Date.now()) {
  for (const [k, v] of seen) if (v.expiresAt && v.expiresAt <= now) seen.delete(k);
}

/** برای سنجه‌ها و عیب‌یابی — چند کد همین حالا در آینه است */
export function mirrorSize() {
  return seen.size;
}

/** فقط برای آزمون: آینه را خالی کن */
export function resetMirror() {
  seen.clear();
}

/**
 *  کدِ ردیف‌های **سرورِ حساب** را در فهرست می‌نشاند.
 *
 *  `ask(source, id)` باید کدِ خام را برگرداند (یا رشتهٔ خالی) و
 *  `onReveal(source, id)` یک بار — و فقط بارِ اول — صدا زده می‌شود تا
 *  ممیزی همان یک ردیف را بگیرد.
 */
export async function mirrorAccountCodes(rows, ask, onReveal, now = Date.now()) {
  pruneCodes(now);
  let asked = 0;
  const out = [];
  for (const row of rows) {
    //  ⛔ فقط کدِ زنده، و فقط دفترهای سرورِ حساب
    const eligible = row.source !== 'panel' && row.status === 'live' && row.canReveal;
    if (!eligible || row.code) { out.push(row); continue; }

    const hit = cachedCode(row.source, row.id, now);
    if (hit) { out.push({ ...row, code: hit, mirrored: true }); continue; }

    //  ⛔ سقفِ هر دور — بقیه دورِ بعد، نه یک رگبارِ شصت‌تایی
    if (asked >= MAX_PER_PASS) { out.push(row); continue; }
    asked += 1;

    let code = '';
    try {
      code = await ask(row.source, row.id);
    } catch {
      //  ⛔ کد رفاه است، فهرست اصل — و دکمهٔ دستی سرِ جایش می‌ماند
      out.push(row);
      continue;
    }
    if (!code) { out.push(row); continue; }

    rememberCode(row.source, row.id, code, row.expiresAt);
    try { onReveal?.(row.source, row.id); } catch { /* ممیزی فهرست را نمی‌شکند */ }
    out.push({ ...row, code, mirrored: true });
  }
  return out;
}
