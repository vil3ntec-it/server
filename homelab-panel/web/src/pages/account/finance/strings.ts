const DICTS: Record<string, FinDict> = { fa, en, ps, ar: en };

/** `t` ِ همین ماژول؛ `{x}` با `vars` پر می‌شود. */
export function useFinT() {
  const { lang } = useApp();
  return useCallback((key: FinKey, vars?: Record<string, string | number>) => {
    let s = (DICTS[lang] || en)[key] ?? fa[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  }, [lang]);
}
export type FinT = ReturnType<typeof useFinT>;
