export const dictionaries: Record<Lang, Dict> = { fa, en, ar, ps };

export function dirOf(lang: Lang): 'rtl' | 'ltr' {
  return LANGUAGES.find((l) => l.code === lang)?.dir ?? 'rtl';
}

export function translate(lang: Lang, key: keyof Dict, vars?: Record<string, string | number>) {
  let text = dictionaries[lang]?.[key] ?? dictionaries.en[key] ?? String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}
