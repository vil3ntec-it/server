//  نرمال‌سازیِ فارسی — پایهٔ همهٔ جست‌وجوها
//
//  چرا لازم است: در فارسی یک کلمه ده‌جور نوشته می‌شود. «می‌شود» با نیم‌فاصله،
//  «میشود» بدونِ آن، «مي‌شود» با یای عربی. اگر نرمال نکنیم، کاربری که «کيبورد»
//  می‌نویسد سندِ «کیبورد» را پیدا نمی‌کند و کلِ جست‌وجو بی‌فایده می‌شود.
//
//  این فایل عمداً هیچ import ی ندارد تا هم در Node و هم داخلِ مرورگر
//  (ویجتِ آفلاین) عیناً همین قاعده‌ها اجرا شوند — دو رفتارِ متفاوت یعنی باگ.
// ═══════════════════════════════════════════════════════════════════════════

const AR_TO_FA = { 'ي': 'ی', 'ك': 'ک', 'ة': 'ه', 'ۀ': 'ه', 'أ': 'ا', 'إ': 'ا', 'آ': 'ا', 'ؤ': 'و', 'ئ': 'ی' };
const DIGITS = { '۰': '0', '۱': '1', '۲': '2', '۳': '3', '۴': '4', '۵': '5', '۶': '6', '۷': '7', '۸': '8', '۹': '9',
                 '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4', '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9' };

/** اعرابِ عربی و کشیده */
const DIACRITICS = /[ً-ٰٟـ]/g;
/** نیم‌فاصله و فاصله‌های نامرئی */
const INVISIBLE = /[​-‏‪-‮﻿]/g;

/** کلماتی که در جست‌وجو ارزشی ندارند و فقط نویز می‌آورند */
const STOPWORDS = new Set([
  'از', 'به', 'با', 'در', 'را', 'که', 'این', 'آن', 'و', 'یا', 'هم', 'تا', 'بر', 'برای',
  'است', 'بود', 'شد', 'شود', 'می', 'های', 'ها', 'یک', 'کن', 'کند', 'کردن', 'دارد', 'دارم',
  'من', 'تو', 'او', 'ما', 'شما', 'چه', 'چی', 'کجا', 'چطور', 'چگونه', 'ایا', 'ایم',
  'the', 'a', 'an', 'is', 'are', 'to', 'of', 'in', 'on', 'for', 'and', 'or', 'how', 'what',
]);

/**
 * متن را به شکلِ یکدستِ قابلِ مقایسه در می‌آورد.
 * @param {string} s
 * @returns {string}
 */
export function normalize(s) {
  if (typeof s !== 'string') return '';
  let out = s.normalize('NFKC');

  out = out.replace(DIACRITICS, '');
  // نیم‌فاصله به فاصله — «می‌شود» و «می شود» یکی می‌شوند. «میشود» را هم پایین‌تر
  // با سه‌گرام می‌گیریم.
  out = out.replace(/‌/g, ' ').replace(INVISIBLE, '');

  let buf = '';
  for (const ch of out) {
    buf += AR_TO_FA[ch] ?? DIGITS[ch] ?? ch;
  }

  return buf
    .toLowerCase()
    // هر چیزی که حرف یا رقم نیست → فاصله
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * ریشهٔ سبکِ فارسی — پسوندهای پرتکرار را برمی‌دارد.
 * عمداً محافظه‌کارانه است: ریشه‌یابیِ تهاجمی در فارسی بیشتر خراب می‌کند تا درست.
 */
export function stem(word) {
  let w = word;
  if (w.length <= 3) return w;
  for (const suf of ['هایی', 'هایم', 'هایت', 'هایش', 'ترین', 'های', 'شان', 'تان', 'مان', 'ها', 'تر', 'ام', 'ات', 'اش']) {
    if (w.length - suf.length >= 3 && w.endsWith(suf)) { w = w.slice(0, -suf.length); break; }
  }
  return w;
}

/**
 * متن → فهرستِ توکن‌های معنادار
 * @param {string} s
 * @param {{keepStopwords?: boolean}} opts
 */
export function tokenize(s, { keepStopwords = false } = {}) {
  const out = [];
  for (const raw of normalize(s).split(' ')) {
    if (!raw) continue;
    if (!keepStopwords && STOPWORDS.has(raw)) continue;
    if (raw.length === 1 && !/\p{N}/u.test(raw)) continue;
    out.push(stem(raw));
  }
  return out;
}

/**
 * سه‌گرامِ نویسه‌ای — تورِ نجاتِ فارسی.
 * «میشود» و «می شود» در سطحِ کلمه فرق دارند ولی سه‌گرام‌هایشان زیاد مشترک است،
 * پس همدیگر را پیدا می‌کنند. غلطِ املاییِ کوچک را هم می‌گیرد.
 */
export function trigrams(s, n = 3) {
  const t = normalize(s).replace(/ /g, '');
  const out = [];
  if (t.length < n) return t ? [t] : [];
  for (let i = 0; i <= t.length - n; i++) out.push(t.slice(i, i + n));
  return out;
}

export { STOPWORDS };
