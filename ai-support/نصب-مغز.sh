#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
#  نصبِ «مغز» دستیارِ هوشمند — لینوکس و مک
#
#      bash نصب-مغز.sh
#
#  همان کاری که نصب-مغز.bat روی ویندوز می‌کند: Ollama را نصب می‌کند، مدلِ
#  مناسبِ همین کامپیوتر را انتخاب و دانلود می‌کند، و ایندکس را می‌سازد.
# ═══════════════════════════════════════════════════════════════════════════
set -uo pipefail
cd "$(dirname "$0")"

echo ""
echo "═══════════════════════════════════════════════════════════"
echo "   نصبِ «مغز» دستیارِ هوشمند"
echo "═══════════════════════════════════════════════════════════"
echo ""
echo "   حجمِ دانلود حدود ۲ تا ۳ گیگابایت است."
echo ""

# ── ۱) Node ────────────────────────────────────────────────────────────────
echo "[۱/۵] بررسیِ Node.js…"
if ! command -v node >/dev/null 2>&1; then
  echo "  ❌ Node.js نصب نیست → https://nodejs.org"
  exit 1
fi
echo "  ✅ Node.js $(node -v)"

# ── ۲) Ollama ──────────────────────────────────────────────────────────────
echo ""
echo "[۲/۵] بررسیِ Ollama…"
if command -v ollama >/dev/null 2>&1; then
  echo "  ✅ Ollama از قبل نصب است"
else
  echo "  نصبش می‌کنم…"
  if ! curl -fsSL https://ollama.com/install.sh | sh; then
    echo "  ❌ نصب نشد. دستی امتحان کن: https://ollama.com/download"
    exit 1
  fi
  echo "  ✅ نصب شد"
fi

# سرویس باید بالا باشد تا pull کار کند
if ! curl -fsS http://127.0.0.1:11434/api/tags >/dev/null 2>&1; then
  echo "  بالا آوردنِ سرویس…"
  (nohup ollama serve >/dev/null 2>&1 &) || true
  for _ in 1 2 3 4 5 6 7 8; do
    sleep 1
    curl -fsS http://127.0.0.1:11434/api/tags >/dev/null 2>&1 && break
  done
fi

# ── ۳) انتخابِ مدل ─────────────────────────────────────────────────────────
echo ""
echo "[۳/۵] بررسیِ سخت‌افزار و انتخابِ مدل…"
MODEL="$(node bin/detect-hardware.mjs --print-model 2>/dev/null || true)"

if [ -z "$MODEL" ]; then
  echo "  ⚠️  رَمِ این کامپیوتر برای مدلِ محلی کافی نیست."
  echo "     دستیار کار می‌کند، ولی جواب‌ها مستقیم از مستندات می‌آیند."
else
  echo "  ✅ مدلِ مناسب: $MODEL"

  # ── ۴) دانلود ────────────────────────────────────────────────────────────
  echo ""
  echo "[۴/۵] دانلودِ مدل — طولانی است، صبر کن…"
  if ! ollama pull "$MODEL"; then
    echo "  ❌ دانلود نشد. اینترنت را بررسی کن و دوباره اجرا کن."
    echo "     (چیزی خراب نشده — از همان‌جا که مانده ادامه می‌دهد.)"
    exit 1
  fi

  echo ""
  echo "  دانلودِ مدلِ جست‌وجوی معنایی…"
  ollama pull nomic-embed-text || echo "  ⚠️  این یکی نشد — جست‌وجو کمی ضعیف‌تر می‌شود."

  node bin/detect-hardware.mjs --apply >/dev/null 2>&1 || true
fi

# ── ۵) ایندکس ──────────────────────────────────────────────────────────────
echo ""
echo "[۵/۵] ساختِ ایندکسِ دانش…"
node bin/build-index.mjs || echo "  ⚠️  ایندکس ساخته نشد — سرویس خودش موقعِ اجرا می‌سازدش."

echo ""
echo "═══════════════════════════════════════════════════════════"
echo "   ✅ تمام شد"
echo "═══════════════════════════════════════════════════════════"
if [ -n "$MODEL" ]; then
  echo ""
  echo "   مغزِ دستیار نصب شد: $MODEL"
  echo "   حالا پنلِ سرور را یک بار ری‌استارت کن."
  echo "   بعدش در سایت: رباتِ دستیار ← تبِ «پشتیبانی هوشمند»"
fi
echo ""
